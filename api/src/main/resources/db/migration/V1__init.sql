CREATE TABLE app_users (
  user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(80) NOT NULL UNIQUE,
  password_hash VARCHAR(200) NOT NULL,
  display_name VARCHAR(120) NOT NULL,
  role VARCHAR(30) NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE parties (
  party_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legal_name VARCHAR(200) NOT NULL,
  corporate_number VARCHAR(20),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE contracts (
  contract_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_contract_id BIGINT REFERENCES contracts(contract_id),
  contract_no VARCHAR(50) NOT NULL UNIQUE,
  name VARCHAR(200) NOT NULL,
  type VARCHAR(50) NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
  start_date DATE,
  end_date DATE,
  amount NUMERIC(18,2),
  currency_code VARCHAR(3) NOT NULL DEFAULT 'JPY',
  auto_renewal BOOLEAN NOT NULL DEFAULT FALSE,
  notice_days INTEGER,
  row_version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_contract_period CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date),
  CONSTRAINT chk_notice_days CHECK (notice_days IS NULL OR notice_days >= 0)
);
CREATE INDEX idx_contracts_status ON contracts(status);
CREATE INDEX idx_contracts_end_date ON contracts(end_date);
CREATE INDEX idx_contracts_parent ON contracts(parent_contract_id);

CREATE TABLE contract_parties (
  contract_party_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contract_id BIGINT NOT NULL REFERENCES contracts(contract_id),
  party_id BIGINT NOT NULL REFERENCES parties(party_id),
  party_role VARCHAR(30) NOT NULL,
  UNIQUE (contract_id, party_id, party_role)
);

CREATE TABLE contract_versions (
  version_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contract_id BIGINT NOT NULL REFERENCES contracts(contract_id),
  version_no INTEGER NOT NULL,
  snapshot_json JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (contract_id, version_no)
);

CREATE TABLE contract_documents (
  document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contract_id BIGINT NOT NULL REFERENCES contracts(contract_id),
  version_id BIGINT REFERENCES contract_versions(version_id),
  file_name VARCHAR(255) NOT NULL,
  storage_key VARCHAR(500) NOT NULL,
  sha256 VARCHAR(64) NOT NULL,
  content_type VARCHAR(120) NOT NULL,
  uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE approval_requests (
  request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contract_id BIGINT NOT NULL REFERENCES contracts(contract_id),
  version_id BIGINT NOT NULL REFERENCES contract_versions(version_id),
  status VARCHAR(30) NOT NULL,
  requested_by BIGINT NOT NULL REFERENCES app_users(user_id),
  requested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  idempotency_key VARCHAR(80),
  UNIQUE (idempotency_key)
);
CREATE UNIQUE INDEX uq_open_approval ON approval_requests(contract_id, version_id)
  WHERE status IN ('REQUESTED', 'IN_PROGRESS');

CREATE TABLE approval_steps (
  step_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT NOT NULL REFERENCES approval_requests(request_id),
  step_order INTEGER NOT NULL,
  approver_id BIGINT NOT NULL REFERENCES app_users(user_id),
  status VARCHAR(30) NOT NULL DEFAULT 'PENDING'
);

CREATE TABLE approval_histories (
  history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT NOT NULL REFERENCES approval_requests(request_id),
  actor_id BIGINT NOT NULL REFERENCES app_users(user_id),
  action VARCHAR(30) NOT NULL,
  comment_text VARCHAR(1000),
  acted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE contract_renewals (
  renewal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contract_id BIGINT NOT NULL REFERENCES contracts(contract_id),
  new_end_date DATE NOT NULL,
  decision VARCHAR(30) NOT NULL,
  decided_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE payment_schedules (
  schedule_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contract_id BIGINT NOT NULL REFERENCES contracts(contract_id),
  due_date DATE NOT NULL,
  amount NUMERIC(18,2) NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'PLANNED'
);

CREATE TABLE audit_logs (
  audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT,
  resource_type VARCHAR(50) NOT NULL,
  resource_id VARCHAR(80) NOT NULL,
  action VARCHAR(50) NOT NULL,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  request_id VARCHAR(80)
);
CREATE INDEX idx_audit_resource ON audit_logs(resource_type, resource_id);

